#!/bin/sh
# Shader-text regression gate.
#
# The emitted GLSL *is* the numerics on this target: docs/performance.md records
# that "semantically identical" text (an inline decode turned into a helper)
# moved VC4 from 283 to 177 MMAC/s and the perplexity with it.  So a change to
# the builders has to be shown to emit the same bytes, not argued to.
#
# Usage:
#   scripts/shader_hashes.sh [engine_binary]              check the golden file
#   scripts/shader_hashes.sh --rebaseline [engine_binary] write it
#   scripts/shader_hashes.sh --show NAME [engine_binary]  print one program
#
# The dump needs no model and no GL context (builders are pure string
# functions), so this runs on the laptop and on the Pi alike.  The output is
# machine independent by construction: the one driver-dependent choice in the
# builders, the q4 shift/and decode, is forced on and off and both texts are
# recorded (q4shift0/..., q4shift1/...) when they differ.
#
# The golden file is scripts/shader_hashes.txt: one FNV-1a/64 digest, the byte
# count and the builder name per line.  A mismatch means the text moved; see it
# with `--show`, or dump everything with `./engine_mm3 --dump-shaders=raw`.
#
# When a text change is deliberate, re-baseline in the same commit and say why
# (PPL, golden string, draws).  A refactor that claims to be text-neutral must
# leave this file untouched.
set -eu
cd "$(dirname "$0")/.."

MODE=check
SHOW=""
case "${1:-}" in
    --check) MODE=check; shift ;;
    --rebaseline) MODE=rebaseline; shift ;;
    --show) MODE=show; SHOW="${2:-}"; [ -n "$SHOW" ] || { echo "--show needs a name" >&2; exit 2; }; shift 2 ;;
    -h|--help) sed -n '2,28p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
esac

BIN="${1:-${BIN:-./engine_mm3}}"
GOLDEN="${GOLDEN:-scripts/shader_hashes.txt}"

if [ ! -x "$BIN" ]; then
    echo "no binary: $BIN (build it, or pass the path)" >&2
    exit 2
fi

# These change the emitted q4 text on purpose.  The golden is the default
# build, so an export in the caller's shell must not decide what it contains.
unset Q4_NOMIN Q4_MV4 Q4_NOUNPACK Q4_BFAST Q4_HFAST 2>/dev/null || true

if [ "$MODE" = show ]; then
    "$BIN" --dump-shaders=raw 2>/dev/null |
        awk -v want="==== $SHOW ====" '
            $0 == want { on = 1; next }
            /^==== / { on = 0 }
            on { print }'
    exit 0
fi

TMP="$(mktemp "${TMPDIR:-/tmp}/shader_hashes.XXXXXX")"
trap 'rm -f "$TMP" "$TMP.golden" "$TMP.diff"' EXIT
"$BIN" --dump-shaders > "$TMP" 2>/dev/null

COUNT=$(grep -c . "$TMP" || true)
if [ "$MODE" = rebaseline ] || [ ! -f "$GOLDEN" ]; then
    {
        echo "# generated by scripts/shader_hashes.sh --rebaseline"
        echo "# digest bytes builder   (FNV-1a/64 of the emitted GLSL)"
        cat "$TMP"
    } > "$GOLDEN"
    echo "shader hashes: wrote $GOLDEN ($COUNT programs)"
    exit 0
fi

# Compare hashes only; the golden's leading comments are not part of the set.
grep -v '^#' "$GOLDEN" > "$TMP.golden" || true
if diff -u "$TMP.golden" "$TMP" > "$TMP.diff"; then
    echo "shader hashes: ok ($COUNT programs, $(wc -c < "$TMP" | tr -d ' ') bytes of digests)"
    exit 0
fi

CHANGED=$(grep -c '^[-+][^-+]' "$TMP.diff" || true)
echo "shader hashes: FAILED - the emitted GLSL moved ($CHANGED lines)" >&2
echo "" >&2
head -40 "$TMP.diff" >&2
echo "" >&2
echo "  see one program:  scripts/shader_hashes.sh --show <name>" >&2
echo "  see all of them:  $BIN --dump-shaders=raw" >&2
echo "  deliberate change: scripts/shader_hashes.sh --rebaseline, and say in" >&2
echo "  the commit what moved (PPL / golden string / draws)." >&2
exit 1
