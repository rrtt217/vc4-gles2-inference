// Which GLSL ES pack/unpack builtins does this driver actually run?
//
// Every language feature the engine might use for a wider residual, a q32
// texture or a cheaper decode has to pass three gates on this board, and they
// are not the same gate:
//
//   1. does the compiler accept it (ESSL version)?
//   2. does the driver link it without falling over?
//   3. does it produce the *right numbers* at draw time?
//
// `roundEven` passed 1 and 2 and then aborted the process, which is why this
// probe renders every function into a 1x1 FBO and compares the result with the
// CPU instead of only compiling it.
//
//   build:  make -C engine probes/packunpack_probe
//   Pi:     make -C engine probes/packunpack_probe_pi CROSS_SYSROOT=<sysroot>
//   run:    ./packunpack_probe [es2|es3|es31|es32]
//
// Modes pick the shader language: es2 = ESSL 1.00, es3 = 300 es, es31 = 310 es,
// es32 = 320 es.  Mesa only gives the higher languages when the override is
// set before eglInitialize, so run
//   MESA_GLES_VERSION_OVERRIDE=3.1 ./packunpack_probe es31
//   MESA_GLES_VERSION_OVERRIDE=3.2 ./packunpack_probe es32
// A driver that claims 3.1 and then rejects a 310 shader is a result too.
#include <EGL/egl.h>
#include <EGL/eglext.h>
#include <GLES2/gl2.h>
#include <cstdint>
#include <cstdio>
#include <cstring>
#include <string>
#include <vector>

#ifndef EGL_PLATFORM_SURFACELESS_MESA
#define EGL_PLATFORM_SURFACELESS_MESA 0x31DD
#endif
typedef EGLDisplay (*PFNGPD)(EGLenum, void*, const EGLint*);
using std::string;

struct Case {
    const char* name;     // printed
    const char* body;     // ESSL 3.00 body; must leave the answer in R (vec4)
    const char* expect;   // the same answer computed on the CPU, for the log
};

// Each body packs its result into R as four bytes / 255, read back exactly.
// `o` is the ESSL 3.00 output; the 1.00 variant is generated by rewriting the
// store only, so a 1.00 run fails where the function itself is missing.
static string wrap(const string& body, const string& ver) {
    string s = "#version " + ver + " es\nprecision highp float;\nprecision highp int;\n";
    s += "out vec4 o;\n";
    s += "vec4 fromUint(highp uint u){return vec4(float((u>>24)&255u),float((u>>16)&255u),"
         "float((u>>8)&255u),float(u&255u))/255.0;}\n";
    s += "vec4 fromInt(highp int v){return fromUint(uint(v));}\n";
    s += "void main(){\nvec4 R=vec4(0.0);\n";
    s += body;
    s += "\no=R;}\n";
    return s;
}

static GLuint compile(GLenum t, const string& s, string& log) {
    GLuint h = glCreateShader(t);
    const char* p = s.c_str();
    glShaderSource(h, 1, &p, nullptr);
    glCompileShader(h);
    GLint ok = 0;
    glGetShaderiv(h, GL_COMPILE_STATUS, &ok);
    if (!ok) {
        char b[2048];
        glGetShaderInfoLog(h, sizeof(b), nullptr, b);
        log = b;
    }
    return ok ? h : 0;
}

static string vs_src(const string& ver) {
    return "#version " + ver + " es\nin vec2 pos;\n"
           "void main(){gl_Position=vec4(pos,0.0,1.0);}\n";
}

static const Case CASES[] = {
    {"shift/and (Q4_SHIFT baseline)",
     "highp uint u = 0xabcdu; R = fromUint(((u>>4)&255u) | ((u&15u)<<8));", "0x0dbc"},
    {"floatBitsToInt",
     "highp int v = floatBitsToInt(1.5); R = fromInt(v);", "0x3fc00000"},
    {"intBitsToFloat",
     "float f = intBitsToFloat(0x3fc00000); R = vec4(f,f,f,1.0)/64.0;", "1.5/64"},
    {"uintBitsToFloat",
     "float f = uintBitsToFloat(0x3fc00000u); R = vec4(f,f,f,1.0)/64.0;", "1.5/64"},
    {"packUnorm2x16 / unpack",
     "highp uint u = packUnorm2x16(vec2(1.0,0.0)); R = fromUint(u);", "0x0000ffff (first comp = low half)"},
    {"unpackUnorm2x16",
     "vec2 v = unpackUnorm2x16(0x8000u); R = vec4(v,v)/4.0;", "~0.5009/4"},
    {"packSnorm2x16 / unpackSnorm",
     "highp uint u = packSnorm2x16(vec2(-1.0,1.0)); R = fromUint(u);", "0x7fff8001 (first comp = low half)"},
    {"unpackSnorm2x16",
     "vec2 v = unpackSnorm2x16(0x7fffu); R = vec4(v,v)/4.0;", "~0.9999/4"},
    {"packHalf2x16",
     "highp uint u = packHalf2x16(vec2(1.0,-2.0)); R = fromUint(u);", "0xc0003c00 (first comp = low half)"},
    {"unpackHalf2x16",
     "vec2 v = unpackHalf2x16(0xc0003c00u); R = vec4(v,v)/8.0+0.5;", "-2,1"},
    {"bitfieldExtract",
     "highp uint u = uint(bitfieldExtract(0xabcd, 4, 8)); R = fromUint(u);", "0xbc (needs 310)"},
    {"roundEven (known to abort on VC4)",
     "float f = roundEven(2.5); R = vec4(f,f,f,1.0)/8.0;", "2.0/8"},
};

int main(int argc, char** argv) {
    setvbuf(stdout, nullptr, _IONBF, 0);
    const string mode = argc > 1 ? argv[1] : "es3";
    const int client = mode == "es2" ? 2 : 3;
    const string ver = mode == "es3" ? "300" : mode == "es31" ? "310"
                     : mode == "es32" ? "320" : "300";
    PFNGPD gpd = (PFNGPD)eglGetProcAddress("eglGetPlatformDisplayEXT");
    if (!gpd) { printf("no eglGetPlatformDisplayEXT\n"); return 1; }
    EGLDisplay d = gpd(EGL_PLATFORM_SURFACELESS_MESA, EGL_DEFAULT_DISPLAY, nullptr);
    EGLint maj = 0, min = 0;
    if (!eglInitialize(d, &maj, &min)) { printf("eglInitialize failed\n"); return 1; }
    eglBindAPI(EGL_OPENGL_ES_API);
    const EGLint ca[] = { EGL_RED_SIZE, 8, EGL_GREEN_SIZE, 8, EGL_BLUE_SIZE, 8,
                          EGL_ALPHA_SIZE, 8, EGL_SURFACE_TYPE, EGL_PBUFFER_BIT,
                          EGL_RENDERABLE_TYPE, EGL_OPENGL_ES2_BIT, EGL_NONE };
    EGLConfig cfg; EGLint n = 0;
    if (!eglChooseConfig(d, ca, &cfg, 1, &n) || n < 1) { printf("eglChooseConfig n=%d\n", n); return 1; }
    const EGLint xa[] = { EGL_CONTEXT_CLIENT_VERSION, client, EGL_NONE };
    EGLContext ctx = eglCreateContext(d, cfg, EGL_NO_CONTEXT, xa);
    if (!ctx) { printf("context failed (client %d)\n", client); return 1; }
    if (!eglMakeCurrent(d, EGL_NO_SURFACE, EGL_NO_SURFACE, ctx)) { printf("makeCurrent failed\n"); return 1; }
    printf("== mode %s ==\n", mode.c_str());
    printf("renderer %s\n", (const char*)glGetString(GL_RENDERER));
    printf("glsl     %s\n", (const char*)glGetString(GL_SHADING_LANGUAGE_VERSION));

    GLuint fbo = 0, tex = 0;
    glGenFramebuffers(1, &fbo);
    glGenTextures(1, &tex);
    glBindTexture(GL_TEXTURE_2D, tex);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA, 1, 1, 0, GL_RGBA, GL_UNSIGNED_BYTE, nullptr);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
    glBindFramebuffer(GL_FRAMEBUFFER, fbo);
    glFramebufferTexture2D(GL_FRAMEBUFFER, GL_COLOR_ATTACHMENT0, GL_TEXTURE_2D, tex, 0);
    if (glCheckFramebufferStatus(GL_FRAMEBUFFER) != GL_FRAMEBUFFER_COMPLETE) {
        printf("fbo incomplete\n"); return 1;
    }
    GLuint vbo = 0;
    glGenBuffers(1, &vbo);
    glBindBuffer(GL_ARRAY_BUFFER, vbo);
    float verts[] = { -1, -1, 3, -1, -1, 3 };
    glBufferData(GL_ARRAY_BUFFER, sizeof(verts), verts, GL_STATIC_DRAW);

    for (const Case& c : CASES) {
        string log;
        GLuint vs = compile(GL_VERTEX_SHADER, vs_src(ver), log);
        GLuint fs = compile(GL_FRAGMENT_SHADER, wrap(c.body, ver), log);
        if (!vs || !fs) {
            printf("%-38s COMPILE FAIL  %s\n", c.name, log.empty() ? "" : log.c_str());
            if (vs) glDeleteShader(vs);
            if (fs) glDeleteShader(fs);
            continue;
        }
        GLuint p = glCreateProgram();
        glAttachShader(p, vs); glAttachShader(p, fs); glBindAttribLocation(p, 0, "pos");
        glLinkProgram(p);
        GLint ok = 0;
        glGetProgramiv(p, GL_LINK_STATUS, &ok);
        if (!ok) {
            char b[2048];
            glGetProgramInfoLog(p, sizeof(b), nullptr, b);
            printf("%-38s LINK FAIL     %s\n", c.name, b);
            glDeleteProgram(p); glDeleteShader(vs); glDeleteShader(fs);
            continue;
        }
        glUseProgram(p);
        glViewport(0, 0, 1, 1);
        glClearColor(0, 0, 0, 0);
        glClear(GL_COLOR_BUFFER_BIT);
        glEnableVertexAttribArray(0);
        glVertexAttribPointer(0, 2, GL_FLOAT, GL_FALSE, 0, nullptr);
        glDrawArrays(GL_TRIANGLES, 0, 3);
        unsigned char px[4] = {0, 0, 0, 0};
        glReadPixels(0, 0, 1, 1, GL_RGBA, GL_UNSIGNED_BYTE, px);
        GLenum err = glGetError();
        printf("%-38s ok  %02x%02x%02x%02x  (expect %s)%s\n",
               c.name, px[0], px[1], px[2], px[3], c.expect,
               err ? "  [GL error]" : "");
        glDeleteProgram(p);
        glDeleteShader(vs);
        glDeleteShader(fs);
    }
    return 0;
}
